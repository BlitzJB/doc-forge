#!/bin/sh
# Deploy site/ to docforge.bharathi.fyi over ONE ssh connection (the VM rate-limits ssh):
# a ControlMaster is opened once and every ssh/rsync below reuses it.
#   DOCFORGE_REMOTE=root@<server> sh site/deploy/deploy.sh            # deploy a release
#   DOCFORGE_REMOTE=root@<server> sh site/deploy/deploy.sh --setup    # first time: certificate + DNS, then deploy
# The server address stays out of the repo: Cloudflare's proxy keeps the origin IP private.
set -eu
cd "$(dirname "$0")/.."
REMOTE="${DOCFORGE_REMOTE:?set DOCFORGE_REMOTE=user@host (the origin server)}"
CM="/tmp/dfssh-%C"   # short: unix socket paths are limited to ~104 bytes
SSH="ssh -o ControlMaster=auto -o ControlPath=$CM -o ControlPersist=10m -o BatchMode=yes"
TS=$(date -u +%Y%m%d%H%M%S)

[ -f downloads/Doc-Forge.dmg ] || { echo "deploy: run npm run site:dmg first" >&2; exit 1; }

# Stage the release locally: only what the page serves.
stage=$(mktemp -d)
trap 'rm -rf "$stage"; $SSH -O exit $REMOTE 2>/dev/null || true' EXIT
mkdir -p "$stage/release/downloads" "$stage/nginx"
cp index.html styles.css main.js "$stage/release/"
cp -R assets "$stage/release/"
cp downloads/Doc-Forge.dmg "$stage/release/downloads/"
(cd "$stage/release/downloads" && shasum -a 256 Doc-Forge.dmg > Doc-Forge.dmg.sha256)
find "$stage/release" -name '.DS_Store' -delete

# CSP: hashes of the page's inline scripts, recomputed every release.
hashes=$(python3 - "$stage/release/index.html" <<'PY'
import re, sys, hashlib, base64
html = open(sys.argv[1]).read()
print(" ".join("'sha256-%s'" % base64.b64encode(hashlib.sha256(s.encode()).digest()).decode()
               for s in re.findall(r"<script>(.*?)</script>", html, re.S)))
PY
)
cat > "$stage/nginx/docforge-csp.conf" <<CSP
# Generated by deploy.sh for release $TS. Do not edit.
add_header Content-Security-Policy "default-src 'none'; script-src 'self' $hashes; style-src 'self'; style-src-attr 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'none'; manifest-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'; upgrade-insecure-requests" always;
CSP
cp deploy/nginx/*.conf "$stage/nginx/"

$SSH -fN $REMOTE   # open the shared connection
RSYNC="rsync -rlt -e"   # plain flags: macOS ships openrsync (no --chmod)
if [ "${1:-}" = "--setup" ]; then
  $SSH $REMOTE 'sh -s' < deploy/setup-remote.sh
fi
$RSYNC "$SSH" --rsync-path="mkdir -p /var/www/docforge/releases && rsync" "$stage/release/" "$REMOTE:/var/www/docforge/releases/$TS/"
$RSYNC "$SSH" "$stage/nginx/" "$REMOTE:/root/docforge-nginx-incoming/"
$SSH $REMOTE "sh -s" <<REMOTE
set -eu
in=/root/docforge-nginx-incoming
files="/etc/nginx/conf.d/docforge-limits.conf /etc/nginx/snippets/docforge-headers.conf /etc/nginx/snippets/docforge-csp.conf /etc/nginx/sites-available/docforge.bharathi.fyi"
bak=\$(mktemp -d)
for f in \$files; do [ -f "\$f" ] && cp -p "\$f" "\$bak/\$(basename \$f)"; done
install -m 644 \$in/docforge-limits.conf /etc/nginx/conf.d/docforge-limits.conf
install -m 644 \$in/docforge-headers.conf \$in/docforge-csp.conf /etc/nginx/snippets/
install -m 644 \$in/docforge.bharathi.fyi.conf /etc/nginx/sites-available/docforge.bharathi.fyi
ln -sfn /etc/nginx/sites-available/docforge.bharathi.fyi /etc/nginx/sites-enabled/docforge.bharathi.fyi
rm -rf \$in
# Never leave nginx with a config that fails its test: the other sites share it.
if ! nginx -t -q; then
  for f in \$files; do
    if [ -f "\$bak/\$(basename \$f)" ]; then cp -p "\$bak/\$(basename \$f)" "\$f"; else rm -f "\$f"; fi
  done
  [ -f /etc/nginx/sites-available/docforge.bharathi.fyi ] || rm -f /etc/nginx/sites-enabled/docforge.bharathi.fyi
  echo "deploy: nginx config test failed; previous config restored" >&2
  exit 1
fi
rm -rf "\$bak"
chown -R root:root /var/www/docforge/releases/$TS
find /var/www/docforge/releases/$TS -type d -exec chmod 755 {} + -o -type f -exec chmod 644 {} +
ln -sfn /var/www/docforge/releases/$TS /var/www/docforge/current.new
mv -T /var/www/docforge/current.new /var/www/docforge/current
# keep the last 5 releases
ls -1d /var/www/docforge/releases/* | sort | head -n -5 | xargs -r rm -rf
systemctl reload nginx
echo "released $TS"
REMOTE
